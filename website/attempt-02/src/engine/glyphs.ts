// Pixel glyph fonts, our own. engine-spec §3.3. Glyph Parts are drawn in `k` and recoloured by Grid.text().

import { mask, type Part } from './ascii';

export interface Font {
  readonly w: number;
  readonly h: number;
  readonly advance: number;
  readonly glyphs: Record<string, Part>;
}

function build(w: number, h: number, src: Record<string, string>): Font {
  const glyphs: Record<string, Part> = {};
  for (const [ch, rows] of Object.entries(src)) {
    const lines = rows.split('/');
    if (lines.length !== h) throw new Error(`glyph ${ch}: ${lines.length} rows, expected ${h}`);
    glyphs[ch] = mask(lines.map((l) => l.padEnd(w, '.')), 'k', `glyph:${ch}`);
  }
  return { w, h, advance: w + 1, glyphs };
}

